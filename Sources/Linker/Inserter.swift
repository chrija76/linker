import AppKit
import Carbon

/// Replaces selected text in the frontmost app by pasting rich text (with or without a link),
/// then puts the user's clipboard back.
@MainActor
enum Inserter {
    struct Piece {
        let text: String
        /// nil pastes the text without a link (removes one).
        let url: URL?
    }

    static func pasteLink(text: String, url: URL?, completion: @escaping () -> Void = {}) {
        Task {
            await paste([Piece(text: text, url: url)]) { _ in true }
            completion()
        }
    }

    /// Pastes each piece in turn over the selection `select(i)` makes; one clipboard save and restore around all of them.
    static func paste(_ pieces: [Piece], select: (Int) -> Bool) async {
        let pb = NSPasteboard.general
        let saved: [[NSPasteboard.PasteboardType: Data]] = (pb.pasteboardItems ?? []).map { item in
            Dictionary(uniqueKeysWithValues: item.types.compactMap { t in item.data(forType: t).map { (t, $0) } })
        }
        await modifiersReleased()

        var ourChange = pb.changeCount
        for (i, piece) in pieces.enumerated() {
            guard select(i) else { continue }
            if pieces.count > 1 { try? await Task.sleep(nanoseconds: 60_000_000) }
            write(piece, to: pb)
            ourChange = pb.changeCount
            postCommandV()
            try? await Task.sleep(nanoseconds: pieces.count > 1 ? 220_000_000 : 50_000_000)
        }

        try? await Task.sleep(nanoseconds: 350_000_000)
        // Only restore if nothing else has written to the clipboard since.
        if pb.changeCount == ourChange {
            pb.clearContents()
            let items = saved.map { types -> NSPasteboardItem in
                let i = NSPasteboardItem()
                for (t, d) in types { i.setData(d, forType: t) }
                return i
            }
            if !items.isEmpty { pb.writeObjects(items) }
        }
    }

    private static func write(_ piece: Piece, to pb: NSPasteboard) {
        let escaped = piece.text.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
        let html: String
        let attributed: NSAttributedString
        if let url = piece.url {
            let href = url.absoluteString.replacingOccurrences(of: "\"", with: "%22")
            html = "<a href=\"\(href)\">\(escaped)</a>"
            attributed = NSAttributedString(string: piece.text, attributes: [.link: url])
        } else {
            html = "<span>\(escaped)</span>"
            attributed = NSAttributedString(string: piece.text)
        }
        let rtf = attributed.rtf(from: NSRange(location: 0, length: attributed.length), documentAttributes: [:])

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(html, forType: .html)
        if let rtf { item.setData(rtf, forType: .rtf) }
        item.setString(piece.text, forType: .string)
        // Ask clipboard managers not to record this paste (nspasteboard.org conventions).
        item.setString("", forType: .init("org.nspasteboard.TransientType"))
        item.setString("", forType: .init("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
    }

    /// The shortcut's ⌃⌥ may still be held; a ⌘V posted then would arrive as ⌃⌥⌘V. Wait up to a second.
    private static func modifiersReleased() async {
        let deadline = Date().addingTimeInterval(1)
        while Date() < deadline {
            let held = CGEventSource.flagsState(.combinedSessionState)
                .intersection([.maskControl, .maskAlternate, .maskShift, .maskCommand])
            if held.isEmpty { return }
            try? await Task.sleep(nanoseconds: 30_000_000)
        }
    }
}
